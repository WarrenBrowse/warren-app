//! See [Opt].

use anyhow::{Context, anyhow};
use clap::Parser;
use std::{ffi::OsString, io::Read, str::FromStr};
use tokio::{fs, io};
use zeroize::Zeroize;

use mullvad_update::format::key;
use mullvad_update::format::response::{Response, SignedResponse};

#[expect(dead_code)]
const DEFAULT_EXPIRY_MONTHS: u32 = 6;

/// Where `sign` reads its key. Never an argument: a command line is readable by
/// every account on the machine for as long as the process runs, and the
/// release runners share their host.
const SIGNING_KEY_VAR: &str = "WARREN_UPDATE_SIGNING_KEY";

/// A tool that generates signed Mullvad version metadata.
#[derive(Parser)]
pub enum Opt {
    /// Generate an ed25519 secret key
    GenerateKey,

    /// Sign a JSON payload using an ed25519 key and output the signed metadata
    /// This data is typically generated by 'generate-unsigned-metadata'.
    /// The secret key is read, as a hexadecimal string, from the
    /// WARREN_UPDATE_SIGNING_KEY environment variable.
    Sign {
        /// File to sign. Use "-" to read from stdin.
        #[clap(short, long)]
        file: String,
    },
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let opt = Opt::parse();

    match opt {
        Opt::GenerateKey => {
            println!("{}", key::SecretKey::generate());
            Ok(())
        }
        Opt::Sign { file } => {
            let secret = signing_key(std::env::var_os(SIGNING_KEY_VAR))?;
            sign(file, secret).await
        }
    }
}

/// The signing key held in the environment variable's `value`. The errors never
/// carry any part of the value.
fn signing_key(value: Option<OsString>) -> anyhow::Result<key::SecretKey> {
    let value = value.with_context(|| format!("{SIGNING_KEY_VAR} is not set"))?;
    let mut value = value
        .into_string()
        .map_err(|_| anyhow!("{SIGNING_KEY_VAR} is not a hexadecimal ed25519 key"))?;
    let secret = key::SecretKey::from_str(value.trim())
        .map_err(|_| anyhow!("{SIGNING_KEY_VAR} is not a hexadecimal ed25519 key"));
    value.zeroize();
    secret
}

async fn sign(file: String, secret: key::SecretKey) -> anyhow::Result<()> {
    // Read unsigned JSON data
    let data = if file == "-" {
        get_stdin().await?
    } else {
        fs::read(file).await?
    };

    // Deserialize version data
    let response: Response =
        serde_json::from_slice(&data).context("Failed to deserialize version metadata")?;

    // Sign it
    let signed_response = SignedResponse::sign(secret, response)?;

    // Print it
    println!(
        "{}",
        serde_json::to_string_pretty(&signed_response)
            .context("Failed to serialize signed version")?
    );

    Ok(())
}

async fn get_stdin() -> io::Result<Vec<u8>> {
    tokio::task::spawn_blocking(|| {
        let mut buf = vec![];
        std::io::stdin().read_to_end(&mut buf)?;
        Ok(buf)
    })
    .await
    .unwrap()
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY: &str = "7777777777777777777777777777777777777777777777777777777777777777";

    #[test]
    fn sign_refuses_a_key_on_the_command_line() {
        let parsed = Opt::try_parse_from([
            "mullvad-version-metadata",
            "sign",
            "--file",
            "unsigned.json",
            "--secret",
            KEY,
        ]);

        assert!(parsed.is_err());
    }

    #[test]
    fn sign_takes_the_file_alone() {
        let parsed = Opt::try_parse_from(["mullvad-version-metadata", "sign", "--file", "-"]);

        assert!(matches!(parsed, Ok(Opt::Sign { file }) if file == "-"));
    }

    #[test]
    fn the_key_is_the_environment_value() {
        let secret = signing_key(Some(format!("{KEY}\n").into())).unwrap();

        assert_eq!(
            secret.pubkey().to_string(),
            "c853ad0f0cd2b619aea92ceec4fd56a24d6499d584ce79257e45cfd8139b60a7"
        );
    }

    #[test]
    fn an_unset_key_is_refused() {
        let error = signing_key(None).err().expect("an unset key is refused");

        assert_eq!(error.to_string(), "WARREN_UPDATE_SIGNING_KEY is not set");
    }

    #[test]
    fn a_malformed_key_is_refused_without_repeating_it() {
        let malformed = format!("{}zz", &KEY[..62]);

        let error = signing_key(Some(malformed.into()))
            .err()
            .expect("a malformed key is refused");

        assert_eq!(
            format!("{error:#}"),
            "WARREN_UPDATE_SIGNING_KEY is not a hexadecimal ed25519 key"
        );
    }
}
